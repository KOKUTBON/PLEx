#!/usr/bin/env python3
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

EXCLUDE = {"README.md", "index.md"}


@dataclass(frozen=True)
class DocEntry:
    filename: str
    title: str
    summary: str


def _extract_title_and_summary(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding="utf-8")
    lines = [line.rstrip() for line in text.splitlines()]

    title = path.stem.replace("_", " ").title()
    for line in lines:
        if line.startswith("# "):
            title = line[2:].strip()
            break

    summary = ""
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        summary = stripped
        break

    if not summary:
        summary = "Documentation reference."
    return title, summary


def _collect_docs() -> list[DocEntry]:
    entries: list[DocEntry] = []
    for path in sorted(DOCS.glob("*.md")):
        if path.name in EXCLUDE:
            continue
        title, summary = _extract_title_and_summary(path)
        entries.append(DocEntry(filename=path.name, title=title, summary=summary))
    return entries


def _render(entries: list[DocEntry]) -> str:
    lines: list[str] = []
    lines.append("# PLEx Documentation Index")
    lines.append("")
    lines.append("This index is auto-generated by `scripts/generate_docs_index.py`.")
    lines.append("")
    lines.append("## Quick Links")
    lines.append("")
    for entry in entries:
        lines.append(f"- [{entry.title}]({entry.filename})")
    lines.append("")
    lines.append("## Documents")
    lines.append("")
    lines.append("| Document | Summary |")
    lines.append("| --- | --- |")
    for entry in entries:
        summary = entry.summary.replace("|", "\\|")
        lines.append(f"| [{entry.title}]({entry.filename}) | {summary} |")
    lines.append("")
    lines.append("## Maintenance")
    lines.append("")
    lines.append("Run this command after adding/updating docs:")
    lines.append("")
    lines.append("```bash")
    lines.append("python3 scripts/generate_docs_index.py")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    entries = _collect_docs()
    output = _render(entries)

    for target_name in ("README.md",):
        target = DOCS / target_name
        target.write_text(output, encoding="utf-8")
        print(f"wrote {target}")


if __name__ == "__main__":
    main()
